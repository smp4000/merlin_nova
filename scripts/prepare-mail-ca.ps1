# Nur Novas eigenes CA-Bündel vorbereiten. Keine Änderung an Windows,
# PHP-Konfiguration oder TLS-Prüfregeln. Download ausschließlich von curl.se;
# aktuelle Mozilla-Vertrauensanker mit veröffentlichter SHA-256 vergleichen.
$ErrorActionPreference = 'Stop'
$novaMailDirectory = Join-Path $PSScriptRoot '../.local/mail'
New-Item -ItemType Directory -Path $novaMailDirectory -Force | Out-Null
$novaCaFile = Join-Path $novaMailDirectory 'ca-bundle.pem'
Invoke-WebRequest -Uri 'https://curl.se/ca/cacert.pem' -OutFile ($novaCaFile + '.download')
$novaChecksum = (Invoke-WebRequest -Uri 'https://curl.se/ca/cacert.pem.sha256').Content
if ($novaChecksum -is [byte[]]) { $novaChecksum = [Text.Encoding]::ASCII.GetString($novaChecksum) }
$novaExpectedHash = ($novaChecksum.Trim() -split '\s+')[0]
$novaActualHash = (Get-FileHash -LiteralPath ($novaCaFile + '.download') -Algorithm SHA256).Hash
if ($novaExpectedHash -notmatch '^[a-fA-F0-9]{64}$' -or $novaActualHash -ne $novaExpectedHash) {
    throw 'CA-Prüfsumme stimmt nicht; vorhandenes Bündel bleibt erhalten.'
}
Move-Item -LiteralPath ($novaCaFile + '.download') -Destination $novaCaFile -Force
# Lokale Virenschutzprüfung kann STRATO-Zertifikate durch ein eigenes ersetzen.
# Ausschließlich bereits von Windows vertraute Norton-Wurzeln übernehmen,
# niemals ein bloß vom Netzwerk geliefertes selbstsigniertes Zertifikat.
$novaLocalRoots = Get-ChildItem Cert:\LocalMachine\Root,Cert:\CurrentUser\Root |
    Where-Object { $_.Subject -eq 'CN=Norton Web/Mail Shield Root, O=Norton Web/Mail Shield, OU=generated by Norton Antivirus for SSL/TLS scanning' } |
    Sort-Object Thumbprint -Unique
foreach ($certificate in $novaLocalRoots) {
    $novaPem = "`n-----BEGIN CERTIFICATE-----`n" + [Convert]::ToBase64String($certificate.RawData, [Base64FormattingOptions]::InsertLineBreaks) + "`n-----END CERTIFICATE-----`n"
    [IO.File]::AppendAllText($novaCaFile, $novaPem, [Text.Encoding]::ASCII)
}
Write-Output 'Nova-Mail: Mozilla-CA-Bündel mit SHA-256 geprüft und vorbereitet.'
